
import streamlit as st
import joblib

# Load trained model
model = joblib.load("models/spam_classifier.pkl")

# Page configuration
st.set_page_config(
    page_title="SpamGuard | AI Spam Detector",
    page_icon="🛡️",
    layout="centered"
)

# Custom CSS
st.markdown("""
<style>
.main {
    background-color: #f7f9fc;
}
.title {
    text-align: center;
    color: #2563eb;
    font-size: 42px;
    font-weight: bold;
}
.subtitle {
    text-align: center;
    color: #64748b;
    font-size: 17px;
}
</style>
""", unsafe_allow_html=True)

# Header
st.markdown('<p class="title">🛡️ SpamGuard</p>', unsafe_allow_html=True)
st.markdown(
    '<p class="subtitle">AI-Powered Spam Message Detection System</p>',
    unsafe_allow_html=True
)

st.write("")
st.info(
    "Protect yourself from unwanted messages using "
    "Machine Learning and Natural Language Processing."
)

# Sidebar
with st.sidebar:
    st.header("About SpamGuard")
    st.write("""
    SpamGuard uses Machine Learning to classify
    text messages into two categories:

    - Spam
    - Not Spam

    **Technologies:**
    - Python
    - Pandas
    - Scikit-learn
    - TF-IDF
    - Naive Bayes
    - Streamlit
    """)

    st.divider()
    st.caption("Internship Project | Codec Technologies")

# Sample messages
st.subheader("Try a sample message")

samples = {
    "Custom message": "",
    "Spam example": "Congratulations! You have won a free prize. Click here to claim now!",
    "Legitimate example": "Hey, are you coming to college tomorrow? We have a project meeting at 10 AM."
}

selected_sample = st.selectbox(
    "Choose a sample or enter your own message:",
    list(samples.keys())
)

# Message input
message = st.text_area(
    "Enter your message:",
    value=samples[selected_sample],
    placeholder="Type or paste your message here...",
    height=150
)

# Prediction
if st.button("🔍 Check Message", use_container_width=True):

    if not message.strip():
        st.warning("Please enter a message before checking.")

    else:
        prediction = model.predict([message])[0]

        st.divider()
        st.subheader("Detection Result")

        if prediction == "spam":
            st.error("🚨 SPAM DETECTED!")
            st.write(
                "Our machine learning model classified "
                "this message as Spam."
            )

        else:
            st.success("✅ NOT SPAM")
            st.write(
                "Our machine learning model classified "
                "this message as Not Spam."
            )

        st.caption(
            "Prediction generated by the trained "
            "TF-IDF and Multinomial Naive Bayes pipeline."
        )

# Footer
st.divider()

st.markdown("### How does it work?")
st.write("""
1. Enter a text message.
2. Click the Check Message button.
3. The trained model analyzes the message.
4. The application displays the predicted category.
""")

st.caption(
    "SpamGuard | Built with Python and Machine Learning | "
    "Educational project using the UCI SMS Spam Collection dataset."
)
